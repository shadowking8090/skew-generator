def _factor_keys(selected_factors):
    if isinstance(selected_factors, str):
        selected_factors = (selected_factors,)
    keys = set()
    for factor in selected_factors:
        key = _NAME_TO_ID.get(factor, factor)
        if key not in FACTOR_PARAMETERS:
            raise KeyError(f"Unknown factor: {factor!r}")
        keys.add(key)
    return tuple(key for key in FACTOR_PARAMETERS if key in keys)


def beta_parameters(mean, sd):
    """Convert valid mean/SD values to beta parameters, including skewed ones."""
    if not np.isfinite(mean) or not 0 < mean < 1:
        raise ValueError("mean must be between 0 and 1")
    if not np.isfinite(sd) or sd <= 0:
        raise ValueError("sd must be finite and positive")
    concentration = mean * (1 - mean) / sd**2 - 1
    alpha, beta = mean * concentration, (1 - mean) * concentration
    if concentration <= 0:
        raise ValueError("sd squared must be less than mean * (1 - mean)")
    return float(alpha), float(beta)


def beta_density(values, mean, sd):
    """Analytical beta PDF; integral 1, zero outside [0, 1].

    f(t) = t**(alpha-1) * (1-t)**(beta-1) / B(alpha, beta).
    A density's height can exceed 1; only display copies are peak scaled.
    """
    alpha, beta = beta_parameters(mean, sd)
    values = np.asarray(values, dtype=float)
    if not np.all(np.isfinite(values)):
        raise ValueError("Evaluation points must be finite")
    inside = (values > 0) & (values < 1)
    t = np.where(inside, values, 0.5)
    log_beta = lgamma(alpha) + lgamma(beta) - lgamma(alpha + beta)
    log_pdf = (alpha - 1) * np.log(t) + (beta - 1) * np.log1p(-t) - log_beta
    density = np.where(inside, np.exp(log_pdf), 0.0)
    # A raw beta can have a boundary singularity. The plotted factor functions
    # below integrate and smooth the original beta instead of clipping its peak.
    density = np.where(values == 0,
                       np.inf if alpha < 1 else (beta if alpha == 1 else 0.0), density)
    density = np.where(values == 1,
                       np.inf if beta < 1 else (alpha if beta == 1 else 0.0), density)
    return density


def _model_parameters(selected_factors=()):
    """Retain source shapes while keeping the existing saturating mean shift.

    Multiple selections pool source beta exponents using shift weights, then
    use the same horizontal adjustment as a single factor. This is an explicit
    synthetic shape rule, not an estimated interaction between the factors.
    """
    if not np.isfinite(BIAS_STRENGTH) or BIAS_STRENGTH < 0:
        raise ValueError("BIAS_STRENGTH must be finite and nonnegative")
    if not np.isfinite(MAX_TOTAL_SHIFT) or not 0 < MAX_TOTAL_SHIFT < 0.5:
        raise ValueError("MAX_TOTAL_SHIFT must be between 0 and 0.5")
    keys = _factor_keys(selected_factors)
    baseline_alpha, baseline_beta = beta_parameters(MU, SIGMA)
    if not keys or BIAS_STRENGTH == 0:
        return dict(alpha=baseline_alpha, beta=baseline_beta, offset=0.0,
                    scale=1.0, smoothing_sd=0.0, target_mean=MU,
                    distribution="beta", selected_factors=keys)
    for key in keys:
        p = FACTOR_PARAMETERS[key]
        if not all(np.isfinite(p[field]) for field in ("alpha", "beta", "shift", "extra_sd")):
            raise ValueError("Factor parameters must be finite")
        if min(p["alpha"], p["beta"], p["shift"]) <= 0 or p["extra_sd"] < 0:
            raise ValueError("Shapes and shifts must be positive; extra_sd must be nonnegative")
    shift = sum(FACTOR_PARAMETERS[key]["shift"] for key in keys)
    variance = sum(FACTOR_PARAMETERS[key]["extra_sd"]**2 for key in keys)
    mean = float(MU - MAX_TOTAL_SHIFT * np.tanh(BIAS_STRENGTH * shift / MAX_TOTAL_SHIFT))
    source_alpha = sum(FACTOR_PARAMETERS[key]["shift"] * FACTOR_PARAMETERS[key]["alpha"]
                       for key in keys) / shift
    source_beta = sum(FACTOR_PARAMETERS[key]["shift"] * FACTOR_PARAMETERS[key]["beta"]
                      for key in keys) / shift
    # At the default strength, each single factor uses its original exponents.
    # Lower strength gradually returns both the shape and mean to the baseline.
    blend = min(1.0, BIAS_STRENGTH / 0.25)
    alpha = (1 - blend) * baseline_alpha + blend * source_alpha
    beta = (1 - blend) * baseline_beta + blend * source_beta
    source_mean = alpha / (alpha + beta)
    # The largest affine support that fits [0, 1] at the desired mean. Affine
    # changes preserve beta skewness, unlike fitting a new beta to mean/SD.
    scale = min(1.0, mean / source_mean, (1 - mean) / (1 - source_mean))
    offset = mean - scale * source_mean
    return dict(alpha=float(alpha), beta=float(beta), offset=float(offset),
                scale=float(scale), smoothing_sd=max(0.01, BIAS_STRENGTH * sqrt(variance)),
                target_mean=mean, distribution="shifted_smoothed_beta",
                selected_factors=keys, shape_blend=blend)


@lru_cache(maxsize=128)
def _beta_quadrature(alpha, beta):
    """Integration nodes/weights generated from a beta function, not observations.

    Split at 1/2 and substitute t=u**(1/alpha) on the left, with the mirrored
    substitution on the right. This removes endpoint singularities without
    needing SciPy or embedded curve values.
    """
    nodes, weights = np.polynomial.legendre.leggauss(96)
    u, weights = (nodes + 1) / 2, weights / 2
    left = 0.5 * u**(1 / alpha)
    right = 1 - 0.5 * u**(1 / beta)
    log_beta = lgamma(alpha) + lgamma(beta) - lgamma(alpha + beta)
    left_weights = weights * np.exp(
        alpha * np.log(0.5) - np.log(alpha) - log_beta
        + (beta - 1) * np.log1p(-left))
    right_weights = weights * np.exp(
        beta * np.log(0.5) - np.log(beta) - log_beta
        + (alpha - 1) * np.log(right))
    mass = np.concatenate((left_weights, right_weights))
    return np.concatenate((left, right)), mass / mass.sum()


def _smoothed_beta_density(values, parameters):
    """Evaluate the shifted beta convolved with a small smoothing kernel.

    f(x) is proportional to integral Beta(t; a,b) * Normal(x; offset+scale*t,s) dt.
    The result is normalized over [0, 1]; smoothing rounds the original sharp
    peak while preserving each source function's asymmetric tail.
    """
    values = np.asarray(values, dtype=float)
    if not np.all(np.isfinite(values)):
        raise ValueError("Evaluation points must be finite")
    nodes, weights = _beta_quadrature(parameters["alpha"], parameters["beta"])
    locations = parameters["offset"] + parameters["scale"] * nodes
    sd = parameters["smoothing_sd"]
    z = (values[..., None] - locations) / sd
    density = np.sum(weights * np.exp(-0.5 * z**2), axis=-1) / (sd * sqrt(2 * np.pi))
    # Normalize after restricting the smoothed function to the MSE interval.
    retained_mass = np.array([
        0.5 * (erf((1 - location) / (sd * sqrt(2)))
               - erf(-location / (sd * sqrt(2)))) for location in locations
    ])
    return np.where((values >= 0) & (values <= 1),
                    density / np.dot(weights, retained_mass), 0.0)


def distribution(selected_factors=(), values=x):
    """Evaluate the unscaled probability density at any finite x values."""
    p = _model_parameters(selected_factors)
    if p["smoothing_sd"] == 0:
        return beta_density(values, MU, SIGMA)
    return _smoothed_beta_density(values, p)


def composite_metadata(selected_factors=()):
    """Actual plotted moments, original shape parameters and synthetic adjustments."""
    p = _model_parameters(selected_factors)
    density = composite_density(selected_factors)
    mean = float(_integrate(x * density, x))
    sd = float(np.sqrt(_integrate((x - mean)**2 * density, x)))
    return dict(p, mean=mean, sd=sd, approximation="original_shape_synthetic_adjustment",
                outcome="binary_laterality_mse", bias_strength=BIAS_STRENGTH,
                max_total_shift=MAX_TOTAL_SHIFT)


