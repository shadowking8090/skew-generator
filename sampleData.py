"""Approximate synthetic left-right curves, defined by functions.

No observations or precomputed curves are embedded here. The original beta
shapes are reflected from accuracy to MSE, then moved horizontally toward
the 50/50 baseline. A small smoothing width rounds their sharp boundaries;
they are not refitted to similar, bell-shaped beta distributions.

The original shape parameters come from the research approximations. The
horizontal adjustments, smoothing and combination rule are synthetic choices,
not measured demographic effects or experimental data.

For binary answers, MSE is the fraction wrong. Random chance has mean 0.5.
Run python sampleData.py to preview the baseline and five approximate curves.
"""

