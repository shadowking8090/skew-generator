def composite_density(selected_factors=()):
    """Unit-area density on the 601-point grid for numerical analysis."""
    density = distribution(selected_factors)
    return density / _integrate(density, x)


def peak_scale(density, height=0.9):
    """Scale a display copy to [0, height]; this changes its area."""
    values = np.asarray(density, dtype=float)
    if values.shape != x.shape or not np.all(np.isfinite(values)):
        raise ValueError("Expected 601 finite density values")
    if np.any(values < 0) or values.max() <= 0:
        raise ValueError("Density must be nonnegative with positive mass")
    if not np.isfinite(height) or not 0 < height <= 1:
        raise ValueError("Display height must be between 0 and 1")
    return height * values / values.max()


def composite_curve(selected_factors=()):
    """Peak-scaled curve for the existing graph.py Composite callback."""
    return peak_scale(composite_density(selected_factors), height=1.0)


def perfect_normal(x, mu=MU, sigma=SIGMA):
    """Keep the app's dotted Gaussian reference centered at random chance."""
    return np.exp(-0.5 * ((x - mu) / sigma) ** 2)


def binom(trials, rate, x=x, height=0.9, bw=None, sigma=None):
    """Keep the original smoothed-binomial function available to the app."""
    n, p = int(trials), float(np.clip(rate, 1e-9, 1 - 1e-9))
    if n < 1:
        raise ValueError("trials must be positive")
    values = np.asarray(x, dtype=float)
    k = np.arange(n + 1)
    logpmf = np.array([lgamma(n + 1) - lgamma(i + 1) - lgamma(n - i + 1)
                       for i in k]) + k * np.log(p) + (n - k) * np.log1p(-p)
    if sigma is not None:
        bw = np.sqrt(max(sigma**2 - p * (1 - p) / n, 1e-6))
    else:
        bw = bw or max(0.02, 0.6 / n)
    y = (np.exp(logpmf)[None, :]
         * np.exp(-0.5 * ((values[:, None] - k[None, :] / n) / bw)**2)).sum(axis=1)
    return height * y / y.max()


